#!/usr/bin/env bash
set -euo pipefail

REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
RULES="$REPO/rules/RULES.md"
GUIDE="$REPO/rules/GUIDE.md"
STOP_HOOK="$REPO/hooks/claude/stop-verify.sh"
STOP_HOOK_CMD="\"$STOP_HOOK\""
POOLS_FILE="$REPO/hermes/pools.tsv"
SKILLS=(test-strategy bombadil quality-gate comment-review)
SHARED_SKILLS_DIR="$HOME/.agents/skills"
MARKER='<!-- zynchro/dev rules: generated by install.sh; edit rules/ in the repo and rerun install -->'
STATE_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/zynchro"
POOLS_STATE="$STATE_DIR/pools"
BACKUP_ROOT="$HOME/.zynchro-backups"
MANIFEST="$BACKUP_ROOT/manifest.tsv"
STAMP=$(date +%Y%m%d-%H%M%S)

mode=install
pools_given=false
pools_arg=
drift=0
snapshotted=" "

usage() {
  cat <<EOF
Usage: ./install.sh [--check | --dry-run | --uninstall] [--pools a,b | --no-pools]

Installs the zynchro/dev rules, skills and hooks into Claude Code, omp, Codex and Hermes.

  --check       report anything missing, stale or changed; exit 1 on drift
  --dry-run     print what would change without touching anything
  --uninstall   remove what install created and restore what it moved aside (memory pools are kept)
  --pools LIST  Hermes memory pools to ensure; remembered for later runs (first default: personal,zynch)
  --no-pools    manage no Hermes memory pools; remembered for later runs
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --check) mode=check ;;
    --dry-run) mode=dry-run ;;
    --uninstall) mode=uninstall ;;
    --pools) pools_given=true; pools_arg=${2:?--pools needs a list}; shift ;;
    --no-pools) pools_given=true; pools_arg= ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage >&2; exit 64 ;;
  esac
  shift
done

if $pools_given; then
  pools=$pools_arg
elif [ -f "$POOLS_STATE" ]; then
  pools=$(cat "$POOLS_STATE")
else
  pools=personal,zynch
fi

say() { printf '  %s %s\n' "$1" "$2"; }
changing() { [ "$mode" = install ] || [ "$mode" = uninstall ]; }
problem() { say "✗" "$1"; drift=1; }

combined_rules() {
  printf '%s\n\n' "$MARKER"
  cat "$RULES"
  printf '\n'
  cat "$GUIDE"
}

snapshot() {
  local file=$1 dest="$BACKUP_ROOT/$STAMP$1"
  [ -f "$file" ] || return 0
  case "$snapshotted" in *" $file "*) return 0 ;; esac
  snapshotted="$snapshotted$file "
  if changing; then mkdir -p "$(dirname "$dest")"; cp -p "$file" "$dest"; fi
  say "↺" "copied $file to $dest"
}

move_aside() {
  local target=$1 dest="$BACKUP_ROOT/$STAMP$1"
  if changing; then
    mkdir -p "$(dirname "$dest")"
    mv "$target" "$dest"
    printf '%s\t%s\n' "$target" "$dest" >>"$MANIFEST"
  fi
  say "↺" "moved $target to $dest"
}

restore() {
  local target=$1 saved
  [ -f "$MANIFEST" ] || return 0
  saved=$(awk -F'\t' -v t="$target" '$1 == t {b = $2} END {print b}' "$MANIFEST")
  [ -n "$saved" ] && [ -e "$saved" ] && [ ! -e "$target" ] || return 0
  mv "$saved" "$target"
  awk -F'\t' -v t="$target" -v b="$saved" '!($1 == t && $2 == b)' "$MANIFEST" >"$MANIFEST.tmp" && mv "$MANIFEST.tmp" "$MANIFEST"
  say "↩" "restored $target"
}

link() {
  local src=$1 dst=$2 current=""
  [ -L "$dst" ] && current=$(readlink "$dst")
  case "$mode" in
    check)
      if [ "$current" = "$src" ]; then say "✓" "$dst"; else problem "$dst is not linked to $src"; fi ;;
    uninstall)
      if [ "$current" = "$src" ]; then rm "$dst"; say "−" "removed $dst"; restore "$dst"; fi ;;
    *)
      if [ "$current" = "$src" ]; then say "=" "$dst"; return; fi
      if [ -e "$dst" ] || [ -L "$dst" ]; then move_aside "$dst"; fi
      if changing; then mkdir -p "$(dirname "$dst")"; ln -s "$src" "$dst"; fi
      say "+" "$dst → $src" ;;
  esac
}

generated() {
  local dst=$1 want
  want=$(combined_rules)
  case "$mode" in
    check)
      if [ -f "$dst" ] && [ "$(cat "$dst")" = "$want" ]; then say "✓" "$dst"; else problem "$dst is missing or stale"; fi ;;
    uninstall)
      if [ -f "$dst" ] && head -n 1 "$dst" | grep -qF "$MARKER"; then rm "$dst"; say "−" "removed $dst"; restore "$dst"; fi ;;
    *)
      if [ -f "$dst" ] && [ "$(cat "$dst")" = "$want" ]; then say "=" "$dst"; return; fi
      if [ -e "$dst" ] && ! head -n 1 "$dst" | grep -qF "$MARKER"; then move_aside "$dst"; fi
      if changing; then mkdir -p "$(dirname "$dst")"; printf '%s\n' "$want" >"$dst"; fi
      say "+" "$dst (generated from rules/)" ;;
  esac
}

rewrite_json() {
  local file=$1 program=$2 tmp
  tmp=$(mktemp)
  jq --arg c "$STOP_HOOK_CMD" -f "$REPO/lib/$program.jq" "$file" >"$tmp"
  cat "$tmp" >"$file"
  rm -f "$tmp"
}

claude_hook() {
  local settings=$HOME/.claude/settings.json has=false
  if ! command -v jq >/dev/null; then problem "jq not found; skipped the Claude Stop hook"; return; fi
  if [ -f "$settings" ] && ! jq empty "$settings" 2>/dev/null; then problem "$settings is not valid JSON; skipped the Claude Stop hook"; return; fi
  if [ -f "$settings" ] && jq -e --arg c "$STOP_HOOK_CMD" 'any(.hooks.Stop[]?.hooks[]?; .command == $c)' "$settings" >/dev/null; then has=true; fi
  case "$mode" in
    check)
      if $has; then say "✓" "Claude Stop hook"; else problem "Claude Stop hook missing from $settings"; fi ;;
    uninstall)
      if $has; then
        snapshot "$settings"
        rewrite_json "$settings" remove-stop-hook
        say "−" "removed Claude Stop hook"
      fi ;;
    *)
      if $has; then say "=" "Claude Stop hook"; return; fi
      snapshot "$settings"
      if changing; then
        [ -f "$settings" ] || echo '{}' >"$settings"
        rewrite_json "$settings" add-stop-hook
      fi
      say "+" "Claude Stop hook (runs scripts/verify in repos that opt in)" ;;
  esac
}

hermes_config() {
  local profile=$1 label=${1:-default} current dirs want cfg ours=false has_dir=false
  local -a hp=()
  [ -n "$profile" ] && hp=(-p "$profile")
  if ! current=$(hermes ${hp[@]+"${hp[@]}"} config get agent.coding_instructions 2>/dev/null); then
    problem "could not read Hermes[$label] agent.coding_instructions; left unchanged"; return
  fi
  if ! dirs=$(hermes ${hp[@]+"${hp[@]}"} config get skills.external_dirs --json 2>/dev/null) \
    || ! jq -e 'type == "array"' >/dev/null 2>&1 <<<"$dirs"; then
    problem "could not read Hermes[$label] skills.external_dirs as a list; left unchanged"; return
  fi
  cfg=$(hermes ${hp[@]+"${hp[@]}"} config path 2>/dev/null || true)
  want=$(combined_rules)
  [ "$(printf '%s\n' "$current" | head -n 1)" = "$MARKER" ] && ours=true
  jq -e --arg d "$SHARED_SKILLS_DIR" 'index($d) != null' >/dev/null <<<"$dirs" && has_dir=true

  case "$mode" in
    check)
      if [ "$current" = "$want" ]; then say "✓" "Hermes[$label] coding_instructions"
      elif $ours; then problem "Hermes[$label] coding_instructions are stale; rerun install"
      else problem "Hermes[$label] coding_instructions are not the zynchro rules"; fi
      if $has_dir; then say "✓" "Hermes[$label] reads $SHARED_SKILLS_DIR"; else problem "Hermes[$label] does not read $SHARED_SKILLS_DIR"; fi ;;
    uninstall)
      if $ours; then
        snapshot "$cfg"
        hermes ${hp[@]+"${hp[@]}"} config unset agent.coding_instructions >/dev/null
        say "−" "Hermes[$label] coding_instructions removed"
      fi
      if $has_dir; then
        snapshot "$cfg"
        hermes ${hp[@]+"${hp[@]}"} config set skills.external_dirs "$(jq -c --arg d "$SHARED_SKILLS_DIR" 'map(select(. != $d))' <<<"$dirs")" >/dev/null
        say "−" "Hermes[$label] no longer reads $SHARED_SKILLS_DIR"
      fi ;;
    *)
      if [ "$current" = "$want" ]; then
        say "=" "Hermes[$label] coding_instructions"
      elif [ -z "$current" ] || $ours; then
        snapshot "$cfg"
        if changing; then hermes ${hp[@]+"${hp[@]}"} config set agent.coding_instructions "$want" >/dev/null; fi
        say "+" "Hermes[$label] coding_instructions ← rules/"
      else
        problem "Hermes[$label] already has its own coding_instructions; left unchanged. Merge them by hand or unset them, then rerun"
      fi
      if $has_dir; then
        say "=" "Hermes[$label] reads $SHARED_SKILLS_DIR"
      else
        snapshot "$cfg"
        if changing; then hermes ${hp[@]+"${hp[@]}"} config set skills.external_dirs "$(jq -c --arg d "$SHARED_SKILLS_DIR" '. + [$d]' <<<"$dirs")" >/dev/null; fi
        say "+" "Hermes[$label] reads $SHARED_SKILLS_DIR"
      fi ;;
  esac
}

hermes_pools() {
  local root=${HERMES_HOME:-$HOME/.hermes} name description
  for name in ${pools//,/ }; do
    description=$(awk -F'\t' -v n="$name" '$1 == n {print $2}' "$POOLS_FILE")
    if [ -z "$description" ]; then problem "pool '$name' is not defined in hermes/pools.tsv"; continue; fi
    if [ ! -d "$root/profiles/$name" ]; then
      case "$mode" in
        check) problem "Hermes pool '$name' does not exist"; continue ;;
        uninstall) continue ;;
        dry-run) say "+" "Hermes pool '$name' (cloned from the default profile)"; continue ;;
        install)
          hermes profile create "$name" --clone-from default --description "$description" </dev/null >/dev/null
          say "+" "Hermes pool '$name' (cloned from the default profile)" ;;
      esac
    elif [ "$mode" = uninstall ]; then
      say "·" "kept Hermes pool '$name' and its memory (delete with: hermes profile delete $name)"
    else
      say "=" "Hermes pool '$name'"
    fi
    hermes_config "$name"
  done
  if [ "$mode" = install ]; then
    mkdir -p "$STATE_DIR"
    printf '%s\n' "$pools" >"$POOLS_STATE"
  elif [ "$mode" = uninstall ]; then
    rm -f "$POOLS_STATE"
  fi
}

echo "zynchro/dev $mode from $REPO"

echo "Shared skills ($SHARED_SKILLS_DIR: omp, Codex, Hermes)"
for s in "${SKILLS[@]}"; do link "$REPO/skills/$s" "$SHARED_SKILLS_DIR/$s"; done

if [ -d "$HOME/.claude" ]; then
  echo "Claude Code"
  link "$RULES" "$HOME/.claude/rules/zynchro-rules.md"
  link "$GUIDE" "$HOME/.claude/rules/zynchro-guide.md"
  for s in "${SKILLS[@]}"; do link "$REPO/skills/$s" "$HOME/.claude/skills/$s"; done
  claude_hook
fi

if [ -d "$HOME/.omp/agent" ]; then
  echo "omp"
  link "$RULES" "$HOME/.omp/agent/RULES.md"
  link "$GUIDE" "$HOME/.omp/agent/AGENTS.md"
fi

echo "Codex"
generated "${CODEX_HOME:-$HOME/.codex}/AGENTS.md"

if command -v hermes >/dev/null; then
  echo "Hermes (pools: ${pools:-none})"
  case "$REPO/" in
    "$HOME/Desktop/"*|"$HOME/Documents/"*|"$HOME/Downloads/"*)
      problem "this repo is in a macOS-protected folder; the Hermes gateway runs in the background and hangs reading skills from it. Move the repo to ~/dev, then run ./install.sh --uninstall in the old place and ./install.sh in the new one" ;;
  esac
  hermes_config ""
  hermes_pools
fi

if [ "$drift" -ne 0 ]; then
  if [ "$mode" = check ]; then echo "Drift found. Run ./install.sh to fix it."; else echo "Finished with problems (marked ✗)."; fi
  exit 1
fi
echo "Done."
